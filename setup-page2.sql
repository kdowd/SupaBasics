-- ============================================================================
--  PAGE 2 SETUP  —  run this once in the Supabase SQL Editor
-- ============================================================================
--  Creates the secured table used by page-2-rls.html:
--
--      penguins         RLS OFF  ->  anyone with the key can read AND write
--      penguins_rls_on  RLS ON   ->  anyone can read; nobody can write
--
--  WHY YOU RUN THIS BY HAND: switching RLS on and creating policies is DDL
--  (ALTER TABLE / CREATE POLICY). PostgREST — the API the browser talks to —
--  is a DATA api and cannot run DDL at all, and the publishable key has no
--  permission to. That is a good thing, not a limitation.
--
--  READ THIS BEFORE RUNNING: it DROPS and rebuilds penguins_rls_on. That is
--  safe — the table exists only to be wrecked in class — and it never touches
--  the original penguins table. Rebuilding is also the fix for the empty-table
--  problem described in the note below.
--
--  NOTE ON AN EMPTY SECURED TABLE (important, and a great teaching point):
--  if penguins_rls_on has 0 rows, the browser CANNOT tell the difference
--  between "your read policy allows everything and there is simply nothing to
--  read" and "your read policy blocks everything". Both return an empty list
--  and no error. Filling the table is what makes the comparison meaningful.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. The disposable copy.
-- ----------------------------------------------------------------------------
-- Built with CREATE TABLE AS so every column keeps EXACTLY the same data type
-- as the original, then given its own primary key and auto-numbering.

drop table if exists public.penguins_rls_on;

create table public.penguins_rls_on as
  select * from public.penguins with no data;

alter table public.penguins_rls_on alter column id set not null;
alter table public.penguins_rls_on alter column id add generated by default as identity;
alter table public.penguins_rls_on add primary key (id);

insert into public.penguins_rls_on
  select * from public.penguins order by id;

-- Identity columns do not advance when you insert explicit id values, so push
-- the sequence past 344. Without this the next id would be 1, which already
-- exists, and the insert would fail on the primary key.
do $$
declare seq text;
begin
  seq := pg_get_serial_sequence('public.penguins_rls_on', 'id');
  if seq is not null then
    perform setval(seq, (select max(id) from public.penguins_rls_on));
  end if;
end $$;


-- ----------------------------------------------------------------------------
-- 2. Grants — can the API roles even reach the table?
-- ----------------------------------------------------------------------------
-- Grants and policies are TWO SEPARATE GATES, which is the bit that confuses
-- everybody:
--
--   grants   ->  may this role run SELECT/INSERT/UPDATE/DELETE on the table?
--   policies ->  WHICH ROWS does that operation apply to?
--
-- Adding a policy does NOT take a grant away, and having a grant does NOT get
-- you past a policy. They are checked independently, and a missing grant fails
-- first with error 42501, before any policy is consulted.

grant select, insert, update, delete on public.penguins_rls_on to anon, authenticated;


-- ----------------------------------------------------------------------------
-- 3. Turn RLS ON.
-- ----------------------------------------------------------------------------
-- From this line onward the default is DENY. With no policy, nothing at all is
-- readable or writable.

alter table public.penguins_rls_on enable row level security;


-- ----------------------------------------------------------------------------
-- 4. Exactly ONE policy: everybody may READ.
-- ----------------------------------------------------------------------------
-- PERMISSIVE is the default kind. Multiple permissive policies are OR-ed
-- together, so they can only ever widen access — which is what you want when
-- each one names a different reason somebody is allowed in.

create policy "Penguins are readable by everyone"
  on public.penguins_rls_on
  for select
  to anon, authenticated
  using (true);


-- ----------------------------------------------------------------------------
-- 5. Deliberately NOTHING for insert / update / delete.
-- ----------------------------------------------------------------------------
-- This is the lesson. Because those operations have no permissive policy,
-- Postgres default-denies them. You never write a rule that forbids writing —
-- you simply never permit it.
--
-- Expect two very different behaviours on page 2:
--
--   INSERT  ->  LOUD.   "new row violates row-level security policy" (42501)
--   UPDATE  ->  SILENT. 0 rows affected, and no error at all.
--   DELETE  ->  SILENT. 0 rows affected, and no error at all.
--
-- The silent ones are the dangerous ones: there is no exception to catch, so
-- code that "works fine" can quietly change nothing.


-- ============================================================================
--  VERIFY — run these to see the difference from the inside.
-- ============================================================================

-- Which tables have RLS switched on?
select tablename,
       rowsecurity as rls_enabled
from pg_tables
where schemaname = 'public'
  and tablename in ('penguins', 'penguins_rls_on');

-- What policies exist, and are they permissive or restrictive?
-- Note the `permissive` column: that is the OR/AND distinction in the catalog.
-- PERMISSIVE policies are OR-ed together; RESTRICTIVE ones are AND-ed on top.
select tablename,
       policyname,
       cmd,
       permissive,
       roles,
       qual
from pg_policies
where tablename in ('penguins', 'penguins_rls_on')
order by tablename, cmd;

-- Both should report 344 rows.
select 'penguins'        as table_name, count(*) from public.penguins
union all
select 'penguins_rls_on' as table_name, count(*) from public.penguins_rls_on;


